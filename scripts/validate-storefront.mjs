import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
const html=readFileSync("index.html","utf8"),fa=readFileSync("fa/index.html","utf8"),ar=readFileSync("ar/index.html","utf8"),js=readFileSync("app.js","utf8"),css=readFileSync("styles.css","utf8"),vercel=JSON.parse(readFileSync("vercel.json","utf8"));
assert(html.includes('<html lang="en" dir="ltr">'),"English route is LTR");
assert(fa.includes('<html lang="fa" dir="rtl">'),"Persian route is RTL");
assert(fa.includes('canonical')&&fa.includes('/fa/'),"Persian route has canonical URL");
assert(js.includes('location.assign("/fa/")'),"Language switch opens Persian route");
assert(js.includes('function posterSVG(p)'),"Product-specific SVG poster renderer exists");
assert(!js.includes("productPhotos"),"Unverified external product photo dependencies are removed");
assert(js.includes("بررسی قیمت روز"),"Persian price disclosure exists");
assert(css.includes("backdrop-filter:blur("),"Liquid Glass treatment exists");
assert(vercel.redirects.some(x=>x.source==="/ar"&&x.destination==="/fa/"),"Legacy Arabic route redirects to Persian");
assert(ar.includes('url=/fa/'),"Arabic page redirects to Persian");
assert((html.match(/<article class="product"/g)||[]).length===100,"English page prerenders 100 products");
console.log("DanaTech Persian storefront checks passed.");
