import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
const fa=readFileSync("index.html","utf8"),en=readFileSync("en/index.html","utf8"),js=readFileSync("app.js","utf8"),css=readFileSync("styles.css","utf8"),vercel=JSON.parse(readFileSync("vercel.json","utf8"));
assert(fa.includes('<html lang="fa" dir="rtl">'),"Persian is the default route");
assert(en.includes('<html lang="en" dir="ltr">'),"English route is available");
assert(en.includes('href="https://danatech.vercel.app/en/"'),"English canonical route exists");
assert(js.includes("function posterSVG(p)"),"SVG poster renderer exists");
assert(fa.includes("<svg")&&en.includes("<svg"),"Posters are embedded in static HTML");
assert(!/amazon\\.ae|amazon\\.com|amazonUrl|Amazon/i.test(fa+en+js),"Amazon links and references are removed");
assert(js.includes("https://ig.me/m/"),"Instagram Direct order links are configured");
assert(js.includes("function renderProducts()"),"Category rendering exists");
assert((js.match(/"id":"/g)||[]).length>=100,"100 products are present in the catalogue");
assert(css.includes("fonts.googleapis.com")&&css.includes('"Inter"'),"English display font is configured");
assert(vercel.redirects.some(x=>x.source==="/fa"&&x.destination==="/"),"Legacy Persian route redirects to root");
console.log("DanaTech Iran storefront checks passed.");
